const assert = require('node:assert/strict');
const Luca = require('../luca-mechanics.js');
const machines = [{id:1,progress:20},{id:2,progress:5},{id:3,progress:5},{id:4,progress:100}];
const link = Luca.createLink(machines);
assert.deepEqual([link.a,link.b],[2,3]);
assert.equal(Luca.transferAmount(20,0),5);
assert.equal(Luca.transferAmount(3,0),1);
assert.equal(Luca.transferAmount(20,97),3);
assert.equal(Luca.transferAmount(20,100),0);
assert.equal(Luca.transferAmount(0,0),0);
assert.equal(Luca.addRoundCharge(link,1,5),1);
assert.equal(Luca.addRoundCharge(link,1,5),0);
assert.equal(link.charge,1);
link.charge=3;
assert.equal(Luca.addRoundCharge(link,2,5),0);
const gate=Luca.createLink([{progress:0},{progress:0}],true);
assert.equal(gate.gateMode,true);
const next=Luca.reconnect(link,[{id:1,progress:100},{id:2,progress:40},{id:3,progress:0}]);
assert.deepEqual([next.a,next.b],[3,2]);
assert.equal(next.charge,3);
const dormant=Luca.reconnect(link,[{id:1,progress:100}]);
assert.equal(dormant.dormant,true);
assert.equal(dormant.a,null);
assert.equal(dormant.charge,3,'charge persists while circuit is dormant');
const gateRestore=Luca.reconnect(dormant,[{progress:0},{progress:0}],true);
assert.equal(gateRestore.charge,3,'stored charge carries into gate phase');
console.log('Luca circuit mechanics tests passed.');